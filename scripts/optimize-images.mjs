// Generates responsive WebP variants of public/assets/*.{jpg,png} into public/assets/opt and writes
// src/lib/image-variants.ts (name -> available widths). Originals stay untouched as the fallback.
// Usage: bun run images
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";

const SRC = "public/assets";
const OUT = path.join(SRC, "opt");
const WIDTHS = [480, 960, 1600];
fs.mkdirSync(OUT, { recursive: true });

const manifest = {};
for (const file of fs.readdirSync(SRC).sort()) {
  if (!/\.(jpe?g|png)$/i.test(file)) continue;
  const base = file.replace(/\.[^.]+$/, "");
  const { width = 0 } = await sharp(path.join(SRC, file)).metadata();
  const widths = WIDTHS.filter((w) => w < width);
  widths.push(width); // full size as the largest variant
  manifest[file] = widths;
  for (const w of widths) {
    const out = path.join(OUT, `${base}-${w}.webp`);
    await sharp(path.join(SRC, file)).resize({ width: w, withoutEnlargement: true }).webp({ quality: 78, effort: 5 }).toFile(out);
  }
}
const body = `// Generated by scripts/optimize-images.mjs - do not edit.\nexport const IMAGE_VARIANTS: Record<string, number[]> = ${JSON.stringify(manifest, null, 2)};\n`;
fs.writeFileSync("src/lib/image-variants.ts", body);
console.log(`optimized ${Object.keys(manifest).length} images`);
